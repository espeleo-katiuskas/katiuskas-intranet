package osmmirror

// FixedBoundary is the boundary of a zone that the extracts do not have as a polygon, written down here: the
// zone is the one that Code names, as a boundary with that code in the municipality rule would.
type FixedBoundary struct {
	Code     string
	Polygons []polygon
}

// FixedBoundaries are the boundaries that the extracts of Geofabrik cut: Ceuta is the one, a peninsula whose land
// border with Morocco is made of ways that lie outside the extract of Spain, so the relation of its municipality
// (1822781) is incomplete and `osmium export` cannot make a polygon of it. It is the two rings that the ways
// that are there make (the town and the peninsula of Monte Hacho; the strip that joins them has nothing in it),
// simplified to about twenty metres. Ceuta does not change, so nothing is read from the extract for it. Its code
// is the INE one of its municipality (areas.AutonomousCityCodes says that the zone is the city).
// Data © OpenStreetMap contributors, ODbL.
func FixedBoundaries() []FixedBoundary {
	return []FixedBoundary{{Code: "51001", Polygons: []polygon{{ceutaWest}, {ceutaEast}}}}
}

